// Isolated demonstration only; no production credential or destination.
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const env = { ...process.env,
  NODE_ENV: 'development',
  NEXT_PUBLIC_NEXUS_BOOKING_ENABLED: '1',
  NEXUS_BOOKING_MODE: 'nexus', NEXUS_BOOKING_ORIGIN: process.env.NEXUS_PREVIEW_ENGINE_PORT === '3119' ? 'http://127.0.0.1:3119' : 'http://127.0.0.1:3118',
  NEXUS_BOOKING_BINDINGS: JSON.stringify([{ eventTypeId: 1, username: 'socialfy', slug: 'demonstracao', durationMinutes: 30, token: 'synthetic_local_preview_token_000000000001' }]),
};
// Static assets were generated by the preview bootstrap; launch Next directly so
// shutdown reaches the owned child and does not leave a Yarn grandchild behind.
const child = spawn(process.execPath, [root + 'node_modules/next/dist/bin/next', 'dev', '--turbopack', '--hostname', '127.0.0.1', '--port', '3117'], { cwd: root + 'apps/web', env, stdio: 'inherit' });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
child.on('exit', (code) => { process.exitCode = code ?? 1; });
